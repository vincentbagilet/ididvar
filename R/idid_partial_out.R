#' Partial out controls
#'
#' @description
#' Compute the partialled out version of a variable based on the regression
#' model provided.
#'
#' @details
#' The regression is first transformed into its control form, an equivalent
#' linear regression (see \code{idid_to_cf}). The variable is then partialled
#' out of the fixed effects and controls of this regression, without
#' re-estimating the model.
#'
#' If `var_interest` is specified (and different from `var_to_partial`),
#' `var_interest` is not partialled out. This is especially interesting if one
#' wants to partial out controls but not the variable of interest.
#'
#' @param reg A regression object (or its control form, returned by
#' \code{idid_to_cf}).
#' @param var_to_partial A string. The name of the variable for which to
#' compute a partialled out version (the outcome or a regressor).
#' @param var_interest A vector string. The name of the variables of interest
#' (coefficient names, eg `treat:post`, or variable names, eg `x` for `fit_x`).
#' @param ... Not used.
#' @param partial_iv A boolean. If TRUE, partials out the part of the
#' endogenous variables that are not explained by the instruments. If the
#' regression is not an IV (or not generated by `AER::ivreg` or `fixest::feols`
#' with an instrumented part), the value of `partial_iv` has no impact on the
#' outcome of the function.
#'
#' @returns
#' A vector of the partialled out version of `var_to_partial` (NA for
#' observations not used for estimation).
#'
#' @export
#'
#' @examples
#' # example with a lm regression
#' reg_ex_lm <- ggplot2::txhousing |>
#'   lm(formula = log(sales) ~ median + listings + city + as.factor(date))
#'
#' idid_partial_out(reg_ex_lm, "median") |>
#'  head()
#'
#' idid_partial_out(reg_ex_lm, "log(sales)", "median") |>
#'  head()
#'
#' # example with a fixest regression
#' reg_ex_fixest <- ggplot2::txhousing |>
#'   fixest::feols(fml = log(sales) ~ median + listings |  as.factor(date) + city)
#'
#' idid_partial_out(reg_ex_fixest, "median") |>
#'   head()
#'
#' idid_partial_out(reg_ex_fixest, "log(sales)", "median") |>
#'   head()
idid_partial_out <- function(reg,
                             var_to_partial,
                             var_interest = var_to_partial,
                             partial_iv = TRUE,
                             ...) {
  reg_cf <- if (inherits(reg, "idid_cf")) reg else idid_to_cf(reg)
  var_interest <- idid_coef_names(reg_cf, var_interest)
  x <- reg_cf$x

  #remove the control function
  if (!partial_iv) {
    x <- x[, setdiff(colnames(x), reg_cf$cf_names), drop = FALSE]
  }

  #y or one of the x
  if (var_to_partial %in% c(reg_cf$y_name, all.vars(str2lang(reg_cf$y_name)))) {
    partialled_out <- reg_cf$y
  } else {
    partialled_out <- x[, idid_coef_names(reg_cf, var_to_partial)]
  }

  #partial out fixed effects
  if (!is.null(reg_cf$fixef_id)) {
    demeaned <- fixest::demean(
      cbind(partialled_out, x),
      f = reg_cf$fixef_id,
      weights = reg_cf$weights
    )
    partialled_out <- demeaned[, 1]
    x[] <- demeaned[, -1]
  }

  #partial out controls
  controls <- x[, setdiff(colnames(x), var_interest), drop = FALSE]
  if (ncol(controls) > 0) {
    partialled_out <-
      stats::lm.wfit(controls, partialled_out, reg_cf$weights)$residuals
  }

  #add NAs back for observations not used for estimation
  miss_val <- rep(NA, reg_cf$nobs_origin)
  miss_val[reg_cf$obs] <- partialled_out

  return(miss_val)
}
